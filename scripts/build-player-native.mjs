// Deterministic, dependency-free bundler for our bounded ES module syntax only.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createNativeBridge} from '../plugin/player-native-bridge.mjs';
import {nativeClientFactory} from '../plugin/native-client-source.mjs';
import {createNotificationClient,showNotificationToast} from '../isolated/web/notifications.mjs';
import {nativeFrameBootstrap} from '../plugin/native-frame-source.mjs';
const root=path.resolve(import.meta.dirname,'..'),web=path.join(root,'isolated/web');
export async function compileNativePlayer(){
  await fs.copyFile(path.join(root,'core/condition-ast.mjs'),path.join(web,'condition-ast.mjs'));
  const modules=new Map(),sources=[];
  async function compile(name){
    if(modules.has(name))return modules.get(name);
    if(!/^[\w-]+\.mjs$/.test(name))throw Error('Unsupported module path '+name);
    const file=path.join(web,name),source=(await fs.readFile(file,'utf8')).replaceAll('\r\n','\n'),id='m'+modules.size;modules.set(name,id);
    const imports=[];let body=source.replace(/^import\s+\{([^}]+)\}\s+from\s+['"]\.\/([^'"]+)['"];?\s*$/gm,(_,names,dependency)=>{imports.push({names,dependency});return '';});
    let bindings='';for(const item of imports){const dep=await compile(item.dependency);bindings+=`const {${item.names.replace(/\bas\b/g,':')}}=${dep};\n`;}
    body=body.replace(/^import\s+['"]\.\/([^'"]+)['"];?\s*$/gm,(_,dependency)=>{throw Error('Side effect import must be explicit named import: '+dependency);});
    const exported=[];body=body.replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let)\s+([A-Za-z_$][\w$]*))/gm,(_,name)=>{exported.push(name);return '';});
    if(/^\s*(?:import|export)\s/m.test(body))throw Error('Unsupported module syntax '+name);
    sources.push(`const ${id}=(()=>{${bindings}\n${body}\nreturn {${exported.join(',')}};})();`);return id;
  }
  await compile('app.mjs');
  const script=`(${nativeFrameBootstrap.toString()})();\n${sources.join('\n')}`;
  const hash=createHash('sha256').update(script).digest('base64');
  let html=await fs.readFile(path.join(web,'index.html'),'utf8');
  html=html.replace(/<script\b[^>]*\bsrc=["'][^"']+["'][^>]*><\/script>/g,'');
  const cssLinks=[...html.matchAll(/<link\b[^>]*href=["']\/?([^"']+\.css)["'][^>]*>/g)];
  for(const match of cssLinks){if(!/^[\w-]+\.css$/.test(match[1]))throw Error('Unsupported stylesheet');const css=await fs.readFile(path.join(web,match[1]),'utf8');html=html.replace(match[0],`<style>${css.replaceAll('</style','<\\/style')}</style>`);}
  html=html.replace('<head>',`<head><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${hash}'; style-src 'unsafe-inline'; img-src data:; frame-src 'self' about:; connect-src 'none'; font-src 'none'; base-uri 'none'; form-action 'none'">`);
  if(/<\/script/i.test(script))throw Error('Unsafe script closing sequence');
  html=html.replace('</body>',`<script>${script}</script></body>`);
  const client=`// GENERATED by node scripts/build-player-native.mjs; edit native source files or shared isolated/web instead.\n(()=>{window.__ModuleLoader__.load({id:'@local/dsh-scean',factory(require){return (${nativeClientFactory.toString()})(require('react'),${JSON.stringify(html)},${createNativeBridge.toString()},${createNotificationClient.toString()},${showNotificationToast.toString()});}});})();\n`;
  return {client,html,modules:[...modules.keys()]};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){const result=await compileNativePlayer();await fs.writeFile(path.join(root,'plugin/client.js'),result.client);console.log(JSON.stringify({nativeSharedModules:result.modules,bytes:Buffer.byteLength(result.client),installed:false}));}
